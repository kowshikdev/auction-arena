// Turns data/players-ipl-2027.csv into a seed migration that calls _import_players().
// Usage: node scripts/build-player-seed.mjs
import { readFileSync, writeFileSync } from "node:fs";

const SEASON = "ipl-2027";
const src = new URL("../data/players-ipl-2027.csv", import.meta.url);
const out = new URL("../supabase/migrations/20261116000006_seed_players.sql", import.meta.url);

const [header, ...lines] = readFileSync(src, "utf8").trim().split(/\r?\n/);
const keys = header.split(",");
const rows = lines.map((line) => {
  const cells = line.split(",");
  return Object.fromEntries(keys.map((key, i) => [key, (cells[i] ?? "").trim()]));
});

const json = JSON.stringify(rows).replaceAll("'", "''");
writeFileSync(
  out,
  `-- Generated by scripts/build-player-seed.mjs from data/players-ipl-2027.csv. Do not edit by hand.\n` +
    `-- Squads are the IPL 2026 rosters; roles, base prices and marquee flags are editable in the admin panel.\n` +
    `select public._import_players('${SEASON}', '${json}'::jsonb);\n`,
);
console.log(`wrote ${rows.length} players`);
